/**
 * 反引号片段里，哪些是**键盘上的键**（界面渲染成 `<kbd>`）。
 *
 * 这份正文里的反引号有两种：按键（`Ctrl+K` / `N` / `空格`）与代码名
 * （`data\` / `WORKLIFE_ROOT` / `99+`）。界面要求"键盘键写成 `<kbd>` 小标签、
 * 别只写纯文本"，所以必须能把两者分开——判据放在这里，界面与单测共用。
 */
const SPECIAL_KEYS = ['Esc', '回车', '空格', 'Tab']

/** 修饰键的显示写法（`Ctrl+回车` 这类组合要靠它识别） */
const MODIFIER_KEYS = ['Ctrl', 'Alt', 'Shift', 'Meta']

export function isKeyboardKey(text: string): boolean {
  const value = text.trim()
  if (value === '') return false
  if (SPECIAL_KEYS.includes(value)) return true
  const parts = value.split('+').map((part) => part.trim())
  if (parts.some((part) => part === '')) return false
  // 单颗键：只有一个字母或数字（N / T / 1 / 2 / 3）。`99+` 这种不算。
  if (parts.length === 1) return /^[A-Z0-9]$/.test(value)
  // 组合键：第一个必须是修饰键（Ctrl+回车 / Ctrl+Alt+M）
  const hasModifier = MODIFIER_KEYS.includes(parts[0] ?? '')
  return hasModifier && parts.length >= 2
}

export type GuideInlineToken =
  | { kind: 'text'; text: string }
  | { kind: 'bold'; text: string }
  | { kind: 'code'; text: string }
  | { kind: 'key'; text: string }

/**
 * 把一段正文拆成内联片段。
 *
 * 只认两种标记：`**加粗**` 与反引号。**不认识的标记原样留在文本里**
 * （宁可让用户看见一个星号，也不要把正文吃掉）——因此
 * `renderInlineMarkdown(parseInline(text)) === text` 对这份正文恒成立，
 * 单测拿它当"生成过程不会改写正文"的证据。
 */
export function parseInline(text: string): GuideInlineToken[] {
  const tokens: GuideInlineToken[] = []
  let rest = text
  let buffer = ''

  const flushBuffer = (): void => {
    if (buffer !== '') {
      tokens.push({ kind: 'text', text: buffer })
      buffer = ''
    }
  }

  while (rest !== '') {
    const boldAt = rest.indexOf('**')
    const codeAt = rest.indexOf('`')

    if (boldAt < 0 && codeAt < 0) {
      buffer += rest
      rest = ''
      break
    }

    if (boldAt >= 0 && (codeAt < 0 || boldAt <= codeAt)) {
      const close = rest.indexOf('**', boldAt + 2)
      if (close < 0) {
        // 没闭合：当普通文本，别吞掉后面的内容
        buffer += rest.slice(0, boldAt + 2)
        rest = rest.slice(boldAt + 2)
        continue
      }
      buffer += rest.slice(0, boldAt)
      flushBuffer()
      tokens.push({ kind: 'bold', text: rest.slice(boldAt + 2, close) })
      rest = rest.slice(close + 2)
      continue
    }

    const close = rest.indexOf('`', codeAt + 1)
    if (close < 0) {
      buffer += rest.slice(0, codeAt + 1)
      rest = rest.slice(codeAt + 1)
      continue
    }
    buffer += rest.slice(0, codeAt)
    flushBuffer()
    const inner = rest.slice(codeAt + 1, close)
    tokens.push({ kind: isKeyboardKey(inner) ? 'key' : 'code', text: inner })
    rest = rest.slice(close + 1)
  }

  flushBuffer()
  return tokens
}

/** 内联片段还原成 md 写法（`**加粗**` / 反引号） */
export function renderInlineMarkdown(tokens: GuideInlineToken[]): string {
  return tokens
    .map((token) => {
      if (token.kind === 'bold') return `**${token.text}**`
      if (token.kind === 'code' || token.kind === 'key') return `\`${token.text}\``
      return token.text
    })
    .join('')
}

/** 去掉内联标记之后的纯文本（给"目录 / 搜索 / 断言"这类不需要格式的地方用） */
export function plainInline(text: string): string {
  return parseInline(text)
    .map((token) => token.text)
    .join('')
}

