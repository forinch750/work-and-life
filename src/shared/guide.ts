/** 列表项先把续行缩进对齐，md 才把它当同一项（否则续行会被当成新段落） */
function indentContinuation(text: string, indent: number): string {
  const pad = ' '.repeat(indent)
  return text
    .split('\n')
    .map((line, index) => (index === 0 ? line : `${pad}${line}`))
    .join('\n')
}

function renderBlockMarkdown(block: GuideBlock): string {
  if (block.kind === 'paragraph') {
    const prefix = block.pending === true ? PENDING_MARK : ''
    return `${prefix}${block.text}`
  }

  if (block.kind === 'list') {
    const lines: string[] = []
    let number = 0
    for (const item of block.items) {
      const prefix = item.pending === true ? PENDING_MARK : ''
      const marker = block.ordered === true ? `${(number += 1)}.` : '-'
      const indent = item.level === 1 ? 2 : 0
      lines.push(
        `${' '.repeat(indent)}${marker} ${indentContinuation(`${prefix}${item.text}`, indent + (block.ordered === true ? 3 : 2))}`
      )
    }
    return lines.join('\n')
  }

  if (block.kind === 'table') {
    const head = `| ${block.head.join(' | ')} |`
    const divider = `|${block.head.map(() => '---').join('|')}|`
    const rows = block.rows.map((row) => `| ${row.join(' | ')} |`)
    return [head, divider, ...rows].join('\n')
  }

  if (block.kind === 'code') {
    return ['```', ...block.lines, '```'].join('\n')
  }

  if (block.kind === 'quote') {
    // 引用块的每一行都要带 `>`，否则第二行会掉到引用块外面
    return block.text
      .split('\n')
      .map((line) => `> ${line}`)
      .join('\n')
  }

  return `### ${block.title}`
}

/**
 * 生成 `操作指南-正文.md` 的全文。
 *
 * 生成结果**不带 BOM、用 LF**（`writeFileSync(..., 'utf8')` 天然如此），
 * 与仓库里其它源码一致；单测直接拿它和磁盘上的文件逐字比对。
 */
export function renderGuideMarkdown(doc: GuideDocument = GUIDE): string {
  const parts: string[] = [`# ${doc.title}`]

  if (doc.preamble.length > 0) {
    parts.push(doc.preamble.map((line) => `> ${line}`).join('\n'))
  }

  for (const chapter of doc.chapters) {
    parts.push('---')
    parts.push(`## ${chapter.index}、${chapter.title}`)
    for (const block of chapter.blocks) parts.push(renderBlockMarkdown(block))
  }

  return `${parts.join('\n\n')}\n`
}

/** 全部章节标题（"一、这个程序是什么"这种写法）；界面目录与单测都用它 */
export function chapterTitle(chapter: GuideChapter): string {
  return `${chapter.index}、${chapter.title}`
}
